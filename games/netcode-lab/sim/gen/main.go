//go:build ignore

// Generates sim/sintab.go: a quarter-wave sine table in Q16.16. The table is
// source code, so native and WASM builds read the same integers.
package main

import (
	"fmt"
	"math"
	"os"
	"strings"
)

func main() {
	var b strings.Builder
	b.WriteString("// Code generated by sim/gen/main.go; DO NOT EDIT.\n\npackage sim\n\n")
	b.WriteString("// sinQuarter[i] = round(sin(i/1024 * pi/2) * 65536), i in 0..1024.\n")
	b.WriteString("var sinQuarter = [1025]int32{")
	for i := 0; i <= 1024; i++ {
		if i%12 == 0 {
			b.WriteString("\n\t")
		}
		fmt.Fprintf(&b, "%d, ", int32(math.Round(math.Sin(float64(i)/1024*math.Pi/2)*65536)))
	}
	b.WriteString("\n}\n")
	os.WriteFile("sintab.go", []byte(b.String()), 0o644)
}
