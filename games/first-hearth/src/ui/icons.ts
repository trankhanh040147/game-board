/** Render an inline SVG string for the given semantic icon name. */
export function icon(name: string | undefined | null, className = 'fh-icon', size?: number): string {
  const key = String(name ?? '').trim();
  const resolved = PATHS[key] ? key : ALIASES[key] ?? 'diamond';
  const inner = PATHS[resolved] ?? PATHS.diamond;
  const style = size ? ` style="width:${size}px;height:${size}px"` : '';
  return `<span class="fh-icon-wrap ${className}"${style} aria-hidden="true">${OPEN}${inner}${CLOSE}</span>`;
}

/** True when the icon exists (or aliases to one). Useful for tests. */
export function hasIcon(name: string): boolean {
  return !!PATHS[name] || !!ALIASES[name];
}

