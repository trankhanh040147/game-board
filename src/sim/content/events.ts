const popAtLeast = (n: number) =>
  ({ kind: 'metric', metric: 'population', op: '>=', value: n }) as const;
const eraAtLeast = (n: number) =>
  ({ kind: 'era', op: '>=', value: n }) as const;
const yearAtMost = (n: number) =>
  ({ kind: 'metric', metric: 'year', op: '<=', value: n }) as const;
const metric = (
  m: string,
  op: '>' | '<' | '>=' | '<=' | '==' | '!=',
  value: number,
) => ({ kind: 'metric', metric: m, op, value }) as const;
const all = (...conditions: EventDef['condition'][]) =>
  ({ kind: 'all', conditions }) as const;
const any = (...conditions: EventDef['condition'][]) =>
  ({ kind: 'any', conditions }) as const;

