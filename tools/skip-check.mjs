import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ headless:true, executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', args:['--no-sandbox','--enable-unsafe-swiftshader'] });
const page = await browser.newPage();
await page.setViewport({width:1600,height:900});
await page.evaluateOnNewDocument(()=>{try{localStorage.clear()}catch{}});
await page.goto('http://127.0.0.1:5280/',{waitUntil:'networkidle2'});
await page.waitForFunction('window.__FIRST_HEARTH__?.ready===true');
await new Promise(r=>setTimeout(r,700));
const state = async (tag) => page.evaluate((t)=>({tag:t, paused:window.__game.paused, speed:window.__game.speed, tick:window.__game.state.tick, tour:!!document.querySelector('.fh-tour'), tourHidden: document.querySelector('.fh-tour')?.style?.display ?? null, key:localStorage.getItem('fh-tour-v1'), pending:window.__game.state.events.pending.length}), tag);
await page.evaluate(()=>document.querySelector('[data-act="begin"]')?.dispatchEvent(new MouseEvent('click',{bubbles:true})));
await new Promise(r=>setTimeout(r,700));
console.log(await state('after-begin'));
await page.evaluate(()=>document.querySelector('[data-act="skip"]')?.dispatchEvent(new MouseEvent('click',{bubbles:true})));
await new Promise(r=>setTimeout(r,400));
console.log(await state('after-skip'));
await page.evaluate(()=>{const g=window.__game; g.resume(); g.setSpeed(2);});
await new Promise(r=>setTimeout(r,400));
console.log(await state('after-resume'));
await new Promise(r=>setTimeout(r,2500));
console.log(await state('2.5s-later'));
await page.screenshot({path:'shots/skip-debug.png'});
await browser.close();
